"""Write test/vectors.txt from code this library did not write.

The signed input follows the API contract v0.31 (§Auth, "The signed input"):

    signed input = <nonce> "\n" "tag=" <tag> "\n" <body>

with both lines always present and empty fields left empty. This script
transcribes that one line with Python's standard hmac module, and checks the
transcription against the contract's three published worked examples before
writing anything. If it cannot reproduce them, it stops.

The public demos at v1.0.2 still sign the older v0.29 shape, so their
chirp_sign.py is no longer a reference for the signed input. It is still used
for what it can prove: its own hmac_sha256() primitive (imported read-only
from the reference clone, run on CPython) produces the "hmac" vectors, and must
agree with Python's hmac.

Usage: python test/oracle.py <path to the Warblet-IoT v1.0.2 clone> [out]
"""
import base64
import hashlib
import hmac
import os
import random
import sys

ref = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "vectors.txt")
sys.path.insert(0, os.path.join(ref, "esp32-generic"))
import chirp_sign  # noqa: E402  the demo's module, unmodified

rng = random.Random(31)


def signed_input(nonce, tag, body):
    """<nonce> "\\n" "tag=" <tag> "\\n" <body>, empty fields left empty (v0.31)."""
    return (str(nonce) if nonce is not None else "").encode() + b"\ntag=" + (tag or "").encode() + b"\n" + body


def mac(key, data):
    return hmac.new(key, data, hashlib.sha256)


# The contract's three worked examples (v0.31 §Auth), byte for byte.
KEY = b"0123456789abcdef0123456789abcdef"
P = b"temp=21.4"
worked = [
    (1757332800123, "snap", "313735373333323830303132330a7461673d736e61700a74656d703d32312e34",
     "1239148f97a361adfb7173445a84a68a4f0b3eb915d626b98e1080f7e6f78e81"),
    (None, None, "0a7461673d0a74656d703d32312e34",
     "fd071ea6328d4ca04bf766d76c4298359a07db6b161fbc8446b336511954bda2"),
    (None, "snap", "0a7461673d736e61700a74656d703d32312e34",
     "aaa23e9e54a70f6c76ff1bfdc282831c3c62c0d574f592fdd831b554bef3e946"),
]
for nonce, tag, input_hex, digest in worked:
    data = signed_input(nonce, tag, P)
    assert data.hex() == input_hex, ("worked example input", nonce, tag, data.hex())
    assert mac(KEY, data).hexdigest() == digest, ("worked example hmac", nonce, tag)

lines = ["# generated by test/oracle.py: v0.31 signed input via Python's hmac (checked against the "
         "contract's worked examples), hmac vectors via the demos' chirp_sign.py; do not edit"]
keys = ["AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8="]  # the demos' example key, bytes 00..1f
keys += [base64.b64encode(bytes(rng.randrange(256) for _ in range(32))).decode() for _ in range(5)]
bodies = [b"\x00\xc9", b"", b"led:on", b"21.53", b"1759363200123\ntag=snap\n",
          bytes(rng.randrange(256) for _ in range(64)), bytes(rng.randrange(256) for _ in range(301))]
nonces = [None, 1759363200123, 1735689600000, 1]
tags = [None, "snap", "heartbeat", "0123456789abcdefghijklmnopqrstuv"]
agreed = 0

for key_b64 in keys:
    key = base64.b64decode(key_b64)
    for body in bodies:
        bh = body.hex() or "-"
        for nonce in nonces:
            for tag in tags:
                expect = mac(key, signed_input(nonce, tag, body)).hexdigest()
                lines.append("header {} {} {} {} {}".format(
                    key_b64, nonce if nonce is not None else "-", tag or "-", bh, expect))
        for tag in tags:
            expect = mac(key, signed_input(None, tag, body)).hexdigest()
            lines.append("envelope {} {} {} {}".format(key_b64, tag or "-", bh, expect))
        # The demos' own HMAC primitive, over plain bodies and over v0.31 inputs.
        for msg in (body, signed_input(1759363200123, "snap", body)):
            demo = chirp_sign.hmac_sha256(key, msg).hex()
            assert demo == mac(key, msg).hexdigest()
            agreed += 1
            lines.append("hmac {} {} {}".format(key_b64, msg.hex() or "-", demo))
    for hwid, nonce in (("sunny-otter-7c2f", 1759363200124), ("A.b_c:9-z", 1735689600001)):
        msg = "chirp-down\n{}\n{}".format(hwid, nonce).encode()  # unchanged by v0.31
        lines.append("poll {} {} {} {}".format(key_b64, hwid, nonce, mac(key, msg).hexdigest()))

with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("oracle: the contract's 3 worked examples reproduced; wrote {} vectors to {}; the demos' "
      "hmac_sha256 and Python's hmac agreed on all {} hmac cases".format(len(lines) - 1, out, agreed))
